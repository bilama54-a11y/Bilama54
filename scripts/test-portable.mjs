import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
await mkdir('.cache', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage', '--no-zygote'], headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.setOffline(true);
const page = await context.newPage();
const errors = []; const requests = [];
page.on('pageerror', error => errors.push(error.message));
context.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
try {
  await page.goto(pathToFileURL(resolve('MatchLab.html')).href, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.outcome-value').count(), 4);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  const before = await page.locator('.outcome-value').first().innerText();
  const xg = page.getByRole('textbox', { name: 'Arsenal — Buts attendus (xG)', exact: true });
  await xg.fill('10,5'); assert.notEqual(await page.locator('.outcome-value').first().innerText(), before); await xg.fill('8,5');
  console.log('PASS fichier local : mobile, hors connexion, calcul automatique');
  const font = (await readFile('public/fonts/dm-sans.woff2')).toString('base64');
  const capture = await context.newPage();
  await capture.setViewportSize({ width: 706, height: 1568 });
  const rows = [['1,6', 'Buts par match', '1,4'], ['8,5', 'Buts attendus (xG)', '7,7'], ['0,8', 'Buts concédés par match', '0,6'], ['4,0', 'xG concédés', '6,5']];
  await capture.setContent(`<style>@font-face{font-family:DM;src:url('data:font/woff2;base64,${font}')}body{margin:0;width:706px;height:1568px;background:white;color:#222;font-family:DM}.team{position:absolute;top:370px;width:250px;text-align:center;font-size:34px}.row{position:absolute;left:0;width:706px;display:grid;grid-template-columns:155px 396px 155px;align-items:center;font-size:28px;text-align:center}.row span:nth-child(2){font-size:25px}</style><div class="team" style="left:40px">Arsenal</div><div class="team" style="right:40px">Leeds</div>${rows.map(([h,label,a],i)=>`<div class="row" style="top:${650+i*90}px"><span>${h}</span><span>${label}</span><span>${a}</span></div>`).join('')}`);
  await capture.evaluate(() => document.fonts.ready); await capture.screenshot({ path: '.cache/portable-offline-fixture.png' }); await capture.close();
  await page.locator('.heading-actions').getByRole('button', { name: 'Importer des captures', exact: true }).click();
  await page.getByLabel('Importer des captures FotMob', { exact: true }).setInputFiles('.cache/portable-offline-fixture.png');
  await page.waitForFunction(() => document.querySelector('.ocr-review') || document.querySelector('.import-file small'), null, { timeout: 60000 });
  assert.ok(await page.locator('.ocr-review').isVisible());
  assert.equal(await page.getByRole('textbox', { name: 'Leeds — import xG concédés', exact: true }).inputValue(), '6,5');
  await page.getByRole('button', { name: 'Appliquer les données', exact: true }).click();
  assert.ok(await page.getByText('Calcul en pause.', { exact: true }).isVisible());
  await page.getByRole('textbox', { name: 'Matchs utilisés · Arsenal', exact: true }).fill('5');
  await page.getByRole('textbox', { name: 'Matchs utilisés · Leeds', exact: true }).fill('5');
  assert.match(await page.locator('.outcome-value').first().innerText(), /%/);
  assert.deepEqual(errors, []); assert.deepEqual(requests, []);
  console.log('PASS OCR réellement embarqué, validation, reprise du calcul, aucune requête réseau');
} finally { await browser.close(); }
